import random
a = sorted(random.sample(range(0, 300), 101))# Генерируем массив из 101 случайного числа (от 0 до 299) и сортируем его
x = 50  # Искомое число
n = len(a)  # Длина массива
print("Начальный список: ", a)
print("Линейный поиск:")
c = 0  # Счетчик количества сравнений
i = -1  # Индекс найденного элемента (-1 означает, что не найден)
for k in range(n):
    c += 1  # Считаем проверку элемента
    if a[k] == x:
        i = k  # Сохраняем позицию, если нашли совпадение
        break  # Выходим из цикла
if i != -1:
    print("Индекс элемента: ", i)
    print("Количество сравнений: ", c)
else:
    print("Число не найдено")
    print("Количество сравнений: ", c)
print("Бинарный поиск:")
l = 0  # Левая (нижняя) граница диапазона поиска
h = n - 1  # Правая (верхняя) граница диапазона поиска
s = 0  # Счетчик количества сравнений
j = -1  # Индекс найденного элемента (-1 означает, что не найден)
while l <= h:
    s += 1  # Считаем итерацию поиска
    m = (l + h) // 2  # Вычисляем индекс середины текущего диапазона
    if a[m] == x:
        j = m  # Нашли элемент, сохраняем его индекс
        break  # Выходим из цикла
    elif a[m] < x:
        l = m + 1  # Сдвигаем левую границу (ищем в правой половине)
    else:
        h = m - 1  # Сдвигаем правую границу (ищем в левой половине)
if j != -1:
    print("Индекс элемента: ", j)
    print("Количество сравнений: ", s)
else:
    print("Число не найдено")
    print("Количество сравнений: ", s)