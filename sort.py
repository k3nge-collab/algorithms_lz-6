import random
a = [random.randint(0, 1000000) for d in range(100)]# a - исходный неотсортированный список
b = a.copy()# b - копия списка для сортировки выбором
c = 0 # c - счетчик перестановок для пузырька
d = 0 # d - индекс текущего элемента для пузырька
print("исходный список: ", a)
print("отсортированный список:")
# Цикл сортировки пузырьком (по убыванию)
while d < len(a) - 1:
    if a[d] < a[d + 1]:
        # Меняем элементы местами, если левый меньше правого
        a[d], a[d + 1] = a[d + 1], a[d]
        c += 1
        d = 0  # Возвращаемся в начало списка
    else:
        d += 1  # Переходим к следующему элементу
print("список пузырьком: ", a)
print("количество операций: ", c)
print()
e = 0 # e - счетчик перестановок для сортировки выбором
print("отсортированный список выбором:")
# Цикл сортировки выбором (по убыванию)
for f in range(len(b)):
    # f - текущая позиция для вставки максимума
    g = f  # g - индекс максимального элемента
    for h in range(f + 1, len(b)):
        if b[h] > b[g]:
            g = h  # Запоминаем индекс нового максимума
    if g != f:
        b[f], b[g] = b[g], b[f]# Меняем местами текущий элемент и найденный максимум
        e += 1
print("отсортированный список выбором: ", b)
print("количество операций: ", e)